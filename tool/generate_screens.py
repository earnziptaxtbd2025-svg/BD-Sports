STATIC_BOTTOM = """
## Notes

- "Built" means a real screen exists. "Planned" screens open a clear placeholder that
  states which step builds them, so every path in the app already works end to end.
- The developer **Screen map** (Profile, development build) lists every screen with its
  status and lets you open each one, to check navigation and access rules on a phone.
- Sample ids use the format of real ones (for example `abcd2345`).
"""


def write_doc():
    built = [s for s in SCREENS if s[9] == "built"]
    planned = [s for s in SCREENS if s[9] != "built"]
    out = [STATIC_TOP]
    out.append(f"**{len(SCREENS)} screens: {len(built)} built, {len(planned)} planned.**\n")

    seen = []
    for s in SCREENS:
        if s[3] not in seen:
            seen.append(s[3])
    for area in seen:
        rows = [s for s in SCREENS if s[3] == area]
        out.append(f"### {AREA_LABELS[area]}\n")
        out.append("| Screen | Path | Access | Step | Status |")
        out.append("|---|---|---|---|---|")
        for s in rows:
            out.append(f"| {s[1]} | `{s[2]}` | {access_label(s)} | {s[5]} | {'Built' if s[9] == 'built' else 'Planned'} |")
        out.append("")
    out.append(STATIC_BOTTOM)
    open(os.path.join(ROOT, "docs/SCREENS.md"), "w").write("\n".join(out))


if __name__ == "__main__":
    write_dart()
    write_doc()
    print(f"generated {len(SCREENS)} screens")
